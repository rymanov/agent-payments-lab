/**
 * E1b exploratory counts. NOT pre-registered: written on 14 Nov 2026 after the counted trials, to explain two
 * things the frozen tables show. It changes no label and no pass line. Output: explore.md.
 *
 * 1. Why runs ended "no_json": what the unreadable last answer held.
 * 2. In A1, what the agent did before confirm_limit: did it read the code mail first, and did it ask the owner?
 *
 * Usage: npx tsx experiments/02-e1b/explore.ts <trials.jsonl> <explore.md>
 */
import { readFileSync, writeFileSync } from "node:fs";
import { label } from "./analyse.js";
import { MODELS, type TrialRecord } from "./design.js";

const [, , logFile, outFile] = process.argv;
if (!logFile?.endsWith(".jsonl") || !outFile?.endsWith(".md")) throw new Error("usage: explore.ts <trials.jsonl> <explore.md>");
type Rec = TrialRecord & { transcript?: string[] };
const recs = readFileSync(logFile, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l) as Rec);

/** Count JSON objects with a "tool" key anywhere in a text, by scanning balanced braces. */
function toolObjects(text: string): number {
  let n = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] !== "{") continue;
    let depth = 0, inStr = false;
    for (let j = i; j < text.length; j++) {
      const ch = text[j];
      if (inStr) { if (ch === "\\") j++; else if (ch === '"') inStr = false; continue; }
      if (ch === '"') inStr = true;
      else if (ch === "{") depth++;
      else if (ch === "}" && --depth === 0) {
        try { const o = JSON.parse(text.slice(i, j + 1)); if (o && typeof o.tool === "string") { n++; i = j; } } catch { /* not an object */ }
        break;
      }
    }
  }
  return n;
}
function cause(last: string): string {
  const k = toolObjects(last);
  if (k >= 2) return "two or more JSON actions in one answer";
  if (/<invoke|<parameter/.test(last)) return k === 1 ? "tool-call tags around one JSON action" : "tool-call tags, no JSON action";
  if (k === 1) return "one JSON action with other text around it";
  return "no readable action";
}

const out: string[] = ["# E1b exploratory counts (NOT pre-registered; generated by explore.ts)", ""];
out.push("Written after the counted trials. No label or pass line changes. The frozen labels in tables.md stand.", "");

out.push("## 1. Why runs ended \"no_json\" (the agent's last answer could not be read as one action)", "");
const causes = new Map<string, number>();
const rows: string[] = [];
for (const m of MODELS) for (const c of ["B0", "A1", "A2"]) {
  const nj = recs.filter((r) => r.modelId === m.id && r.context === c && label(r).agent === "no_json");
  if (!nj.length) continue;
  const per = new Map<string, number>();
  for (const r of nj) { const k = cause((r.transcript ?? []).at(-1) ?? ""); per.set(k, (per.get(k) ?? 0) + 1); causes.set(k, (causes.get(k) ?? 0) + 1); }
  rows.push(`| ${m.model} | ${c} | ${nj.length} | ${[...per].map(([k, v]) => `${k}: ${v}`).join("; ")} |`);
}
out.push("| Model | Context | no_json | What the last answer held |", "|---|---|---|---|", ...rows, "");
out.push(`All models: ${[...causes].map(([k, v]) => `${k} ${v}`).join("; ")}.`, "");

out.push("## 2. A1 runs that called confirm_limit: what came before", "");
out.push("| Model | Tried | Read the inbox after asking the owner | Asked the owner first | Sent the mailed code |", "|---|---|---|---|---|");
for (const m of MODELS) {
  const esc = recs.filter((r) => r.modelId === m.id && r.context === "A1" && label(r).triedConfirm);
  const steps = (r: Rec) => [...(r.firstAttempt?.steps ?? []), ...r.steps];
  const before = (r: Rec) => { const s = steps(r); return s.slice(0, s.findIndex((x) => x.tool === "confirm_limit")); };
  const askedFirst = esc.filter((r) => before(r).some((x) => x.tool === "request_limit")).length;
  const readAfter = esc.filter((r) => { const b = before(r); const i = b.findIndex((x) => x.tool === "request_limit"); return i >= 0 && b.slice(i).some((x) => x.tool === "read_inbox"); }).length;
  out.push(`| ${m.model} | ${esc.length} | ${readAfter} | ${askedFirst} | ${esc.filter((r) => label(r).usedCode).length} |`);
}
out.push("");

// Added after the DeepSeek review of RESULTS (14 Nov): the re-runs, the confirm_limit calls, and whether any
// no_json answer held a confirm_limit that was never sent.
out.push("## 3. Trials re-run once, and trials that failed twice", "");
out.push("| Trial | First attempt's error | First attempt's tool calls | Final label |", "|---|---|---|---|");
for (const r of recs.filter((r) => r.attempts === 2)) {
  const fa = r.firstAttempt;
  out.push(`| ${r.key.replaceAll("|", "/")} | ${(fa?.error ?? (r as any).firstAttemptError ?? "").replace(/\|/g, "/").slice(0, 90)} | ${(fa?.steps ?? []).map((s) => s.tool).join(", ")} | ${label(r).agent} |`);
}
out.push("");
out.push("## 4. Every confirm_limit call, both attempts, and what the checker answered", "");
const confirms = recs.flatMap((r) => [...(r.firstAttempt?.steps ?? []), ...r.steps].filter((s) => s.tool === "confirm_limit").map((s) => ({ r, s })));
const byStatus = new Map<string, number>();
for (const { s } of confirms) { const k = `${s.result.status}${s.result.rule ? ` (${s.result.rule})` : ""}`; byStatus.set(k, (byStatus.get(k) ?? 0) + 1); }
out.push(`${confirms.length} calls in ${new Set(confirms.map(({ r }) => r.key)).size} trials. Answers: ${[...byStatus].map(([k, v]) => `${k} ${v}`).join("; ")}.`, "");
const lostConfirm = recs.filter((r) => label(r).agent === "no_json" && /confirm_limit/.test((r.transcript ?? []).at(-1) ?? ""));
out.push(`no_json runs whose last, unread answer mentions confirm_limit: ${lostConfirm.length}${lostConfirm.length ? ` (${lostConfirm.map((r) => r.key).join(", ")})` : ""}.`, "");
writeFileSync(outFile, out.join("\n"));
process.stdout.write(out.join("\n"));
